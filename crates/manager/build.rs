//! Embeds every built-in mod's `mod.toml` (and `patterns.toml`, if any) from
//! the repository's `mods/` folder, so the manager knows the mods without the
//! game or the DLL. A missing or empty `mods/` folder gives an empty list.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let mods_dir = manifest_dir.join("../../mods");
    println!("cargo:rerun-if-changed={}", mods_dir.display());

    let mut dirs: Vec<PathBuf> = std::fs::read_dir(&mods_dir)
        .map(|rd| {
            rd.flatten()
                .map(|e| e.path())
                .filter(|p| p.join("mod.toml").is_file())
                .collect()
        })
        .unwrap_or_default();
    dirs.sort();

    let mut out = String::from("// Generated by build.rs.\npub static BUILTIN: &[Embedded] = &[\n");
    for d in &dirs {
        println!("cargo:rerun-if-changed={}", d.display());
        let manifest = d.join("mod.toml");
        let patterns = d.join("patterns.toml");
        println!("cargo:rerun-if-changed={}", manifest.display());
        println!("cargo:rerun-if-changed={}", patterns.display());
        let folder = d.file_name().unwrap().to_string_lossy();
        let pat = if patterns.is_file() {
            format!("include_str!({})", lit(&patterns))
        } else {
            "\"\"".to_string()
        };
        writeln!(
            out,
            "    Embedded {{ folder: {folder:?}, manifest: include_str!({}), patterns: {pat} }},",
            lit(&manifest)
        )
        .unwrap();
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("builtin_mods.rs");
    std::fs::write(dest, out).unwrap();
}

/// A path as a Rust string literal (absolute, so `include_str!` finds it).
fn lit(p: &Path) -> String {
    let abs = p.canonicalize().unwrap_or_else(|_| p.to_path_buf());
    format!("{:?}", abs.to_string_lossy())
}
